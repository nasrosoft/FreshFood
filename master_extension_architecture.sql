-- ===============================================================================
-- MASTER (WINDOWS) / EXTENSION (ANDROID) ARCHITECTURE
-- ===============================================================================
-- The Windows desktop app is the MASTER station of the business:
--   * exactly one Windows install is registered as master (app_settings.master_device_id)
--   * every Android install is an EXTENSION that must be approved by the master
--   * the master decides which modules each extension may open (allowed_modules)
--   * the master can revoke a phone at any time (lost phone, driver left, ...)
--   * the master publishes a heartbeat so phones can show whether the PC is online
--
-- Supabase stays the shared data channel between the PC and the phones, because
-- delivery drivers work on the road and cannot reach a PC on the shop LAN.
--
-- Run this script once in the Supabase SQL editor. It is idempotent.
-- ===============================================================================

-- 1. Master columns on app_settings ---------------------------------------------
ALTER TABLE app_settings ADD COLUMN IF NOT EXISTS master_device_id TEXT;
ALTER TABLE app_settings ADD COLUMN IF NOT EXISTS master_heartbeat_at TIMESTAMPTZ;
-- 1 = new phones are approved automatically with the default modules, 0 = PC approval required
ALTER TABLE app_settings ADD COLUMN IF NOT EXISTS auto_approve_extensions INT NOT NULL DEFAULT 0;
-- Modules granted to a newly approved phone
ALTER TABLE app_settings ADD COLUMN IF NOT EXISTS default_extension_modules TEXT[] NOT NULL DEFAULT ARRAY['deliveries'];

-- app_settings used to be writable by anyone (USING true). Brand / licence /
-- master settings must now only be changed by admins.
DROP POLICY IF EXISTS "Allow update access to app_settings" ON app_settings;
DROP POLICY IF EXISTS "Admins update app_settings" ON app_settings;
CREATE POLICY "Admins update app_settings"
ON app_settings FOR UPDATE
USING (is_admin())
WITH CHECK (is_admin());

-- The master PC enables / disables staff accounts.
DROP POLICY IF EXISTS "Admins update profiles" ON profiles;
CREATE POLICY "Admins update profiles"
ON profiles FOR UPDATE
USING (is_admin())
WITH CHECK (is_admin());

-- 2. Device registry --------------------------------------------------------------
CREATE TABLE IF NOT EXISTS devices (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    device_id TEXT UNIQUE NOT NULL,              -- random install id generated by the app
    platform TEXT NOT NULL CHECK (platform IN ('WINDOWS', 'ANDROID')),
    device_name TEXT,
    user_id UUID REFERENCES profiles(id) ON DELETE SET NULL,  -- last user signed in on it
    status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REVOKED')),
    allowed_modules TEXT[] NOT NULL DEFAULT ARRAY['deliveries'],
    app_version TEXT,
    last_seen_at TIMESTAMPTZ DEFAULT NOW(),
    approved_by UUID REFERENCES profiles(id) ON DELETE SET NULL,
    approved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE devices ENABLE ROW LEVEL SECURITY;

-- Admins (the master PC) can read every device; a user can read the devices they use.
DROP POLICY IF EXISTS "Admins read devices" ON devices;
CREATE POLICY "Admins read devices" ON devices FOR SELECT USING (is_admin());
DROP POLICY IF EXISTS "Users read own devices" ON devices;
CREATE POLICY "Users read own devices" ON devices FOR SELECT USING (user_id = auth.uid());
-- No INSERT/UPDATE/DELETE policies: all writes go through the SECURITY DEFINER functions below.


-- 3. Helper: is the caller the master station? -------------------------------------
CREATE OR REPLACE FUNCTION is_master_device(p_device_id TEXT)
RETURNS BOOLEAN AS $$
    SELECT is_admin() AND EXISTS (
        SELECT 1 FROM app_settings
        WHERE id = 1 AND master_device_id IS NOT NULL AND master_device_id = p_device_id
    );
$$ LANGUAGE sql SECURITY DEFINER;


-- 4. register_device: called by every app after login and periodically ---------------
--    * creates the device row on first call
--    * the first Windows install signed in as ADMIN becomes the master automatically
--    * returns what the app must do: status, modules, master info
CREATE OR REPLACE FUNCTION register_device(
    p_device_id TEXT,
    p_platform TEXT,
    p_device_name TEXT,
    p_app_version TEXT
)
RETURNS JSONB AS $$
DECLARE
    v_uid UUID := auth.uid();
    v_is_admin BOOLEAN := is_admin();
    v_settings RECORD;
    v_device RECORD;
    v_status TEXT;
    v_modules TEXT[];
    v_is_master BOOLEAN := FALSE;
BEGIN
    IF v_uid IS NULL THEN
        RAISE EXCEPTION 'Not authenticated';
    END IF;
    IF p_device_id IS NULL OR length(p_device_id) < 8 THEN
        RAISE EXCEPTION 'Invalid device id';
    END IF;
    IF p_platform NOT IN ('WINDOWS', 'ANDROID') THEN
        RAISE EXCEPTION 'Invalid platform';
    END IF;

    SELECT * INTO v_settings FROM app_settings WHERE id = 1;

    SELECT * INTO v_device FROM devices WHERE device_id = p_device_id;

    IF NOT FOUND THEN
        -- Bootstrap: first Windows admin install claims the master role
        IF p_platform = 'WINDOWS' AND v_is_admin AND v_settings.master_device_id IS NULL THEN
            v_status := 'APPROVED';
            v_modules := ARRAY['dashboard','pos','products','purchases','deliveries','customers','inventory','returns','users','settings','devices'];
            UPDATE app_settings SET master_device_id = p_device_id, master_heartbeat_at = NOW() WHERE id = 1;
        ELSIF p_platform = 'ANDROID' AND COALESCE(v_settings.auto_approve_extensions, 0) = 1 THEN
            v_status := 'APPROVED';
            v_modules := COALESCE(v_settings.default_extension_modules, ARRAY['deliveries']);
        ELSE
            v_status := 'PENDING';
            v_modules := COALESCE(v_settings.default_extension_modules, ARRAY['deliveries']);
        END IF;

        INSERT INTO devices (device_id, platform, device_name, user_id, status, allowed_modules, app_version, last_seen_at, approved_at)
        VALUES (p_device_id, p_platform, p_device_name, v_uid, v_status, v_modules, p_app_version, NOW(),
                CASE WHEN v_status = 'APPROVED' THEN NOW() ELSE NULL END)
        RETURNING * INTO v_device;
    ELSE
        UPDATE devices
        SET user_id = v_uid,
            device_name = COALESCE(p_device_name, device_name),
            app_version = COALESCE(p_app_version, app_version),
            last_seen_at = NOW()
        WHERE device_id = p_device_id
        RETURNING * INTO v_device;
    END IF;

    SELECT * INTO v_settings FROM app_settings WHERE id = 1;
    v_is_master := (v_settings.master_device_id = p_device_id);

    IF v_is_master THEN
        UPDATE app_settings SET master_heartbeat_at = NOW() WHERE id = 1;
        v_settings.master_heartbeat_at := NOW();
    END IF;

    -- A staff account disabled on the master locks every phone it uses.
    v_status := v_device.status;
    IF NOT v_is_admin AND EXISTS (SELECT 1 FROM profiles WHERE id = v_uid AND is_active = FALSE) THEN
        v_status := 'REVOKED';
    END IF;

    RETURN jsonb_build_object(
        'device_id', v_device.device_id,
        'status', v_status,
        'allowed_modules', to_jsonb(v_device.allowed_modules),
        'is_master', v_is_master,
        'master_configured', v_settings.master_device_id IS NOT NULL,
        'master_heartbeat_at', v_settings.master_heartbeat_at,
        'master_online', COALESCE(v_settings.master_heartbeat_at > NOW() - INTERVAL '2 minutes', FALSE),
        'app_enabled', COALESCE(v_settings.app_enabled, 1) = 1
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- 5. master_heartbeat: the PC calls this every ~30 s ---------------------------------
CREATE OR REPLACE FUNCTION master_heartbeat(p_device_id TEXT)
RETURNS JSONB AS $$
BEGIN
    IF NOT is_master_device(p_device_id) THEN
        RAISE EXCEPTION 'This device is not the master station';
    END IF;
    UPDATE app_settings SET master_heartbeat_at = NOW() WHERE id = 1;
    UPDATE devices SET last_seen_at = NOW() WHERE device_id = p_device_id;
    RETURN jsonb_build_object('success', true, 'at', NOW());
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- 6. claim_master: move the master role to another Windows PC (admin only) ----------
--    Used when the shop replaces its PC. The old master becomes a normal device.
CREATE OR REPLACE FUNCTION claim_master(p_device_id TEXT)
RETURNS JSONB AS $$
DECLARE
    v_platform TEXT;
BEGIN
    IF NOT is_admin() THEN
        RAISE EXCEPTION 'Only an administrator can claim the master role';
    END IF;
    SELECT platform INTO v_platform FROM devices WHERE device_id = p_device_id;
    IF v_platform IS NULL THEN
        RAISE EXCEPTION 'Unknown device, call register_device first';
    END IF;
    IF v_platform <> 'WINDOWS' THEN
        RAISE EXCEPTION 'Only a Windows station can be the master';
    END IF;

    UPDATE app_settings SET master_device_id = p_device_id, master_heartbeat_at = NOW() WHERE id = 1;
    UPDATE devices
    SET status = 'APPROVED',
        allowed_modules = ARRAY['dashboard','pos','products','purchases','deliveries','customers','inventory','returns','users','settings','devices'],
        approved_by = auth.uid(),
        approved_at = NOW()
    WHERE device_id = p_device_id;
    RETURN jsonb_build_object('success', true, 'master_device_id', p_device_id);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- 7. set_device_access: only the master station approves / revokes extensions --------
CREATE OR REPLACE FUNCTION set_device_access(
    p_master_device_id TEXT,
    p_target_device_id TEXT,
    p_status TEXT,
    p_allowed_modules TEXT[]
)
RETURNS JSONB AS $$
BEGIN
    IF NOT is_master_device(p_master_device_id) THEN
        RAISE EXCEPTION 'Only the master station can change device access';
    END IF;
    IF p_target_device_id = p_master_device_id THEN
        RAISE EXCEPTION 'The master station cannot change its own access';
    END IF;
    IF p_status NOT IN ('PENDING', 'APPROVED', 'REVOKED') THEN
        RAISE EXCEPTION 'Invalid status';
    END IF;

    UPDATE devices
    SET status = p_status,
        -- master-only modules can never be granted to an extension
        allowed_modules = CASE
            WHEN p_allowed_modules IS NULL THEN allowed_modules
            ELSE ARRAY(SELECT m FROM unnest(p_allowed_modules) AS m WHERE m NOT IN ('users', 'settings', 'devices'))
        END,
        approved_by = CASE WHEN p_status = 'APPROVED' THEN auth.uid() ELSE approved_by END,
        approved_at = CASE WHEN p_status = 'APPROVED' THEN NOW() ELSE approved_at END
    WHERE device_id = p_target_device_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Unknown device';
    END IF;
    RETURN jsonb_build_object('success', true);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- 8. delete_device: forget a device (it will re-register as PENDING) -----------------
CREATE OR REPLACE FUNCTION delete_device(p_master_device_id TEXT, p_target_device_id TEXT)
RETURNS JSONB AS $$
BEGIN
    IF NOT is_master_device(p_master_device_id) THEN
        RAISE EXCEPTION 'Only the master station can delete devices';
    END IF;
    IF p_target_device_id = p_master_device_id THEN
        RAISE EXCEPTION 'The master station cannot delete itself';
    END IF;
    DELETE FROM devices WHERE device_id = p_target_device_id;
    RETURN jsonb_build_object('success', true);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- 9. set_extension_policy: auto-approve flag and default modules (master only) -------
CREATE OR REPLACE FUNCTION set_extension_policy(
    p_master_device_id TEXT,
    p_auto_approve INT,
    p_default_modules TEXT[]
)
RETURNS JSONB AS $$
BEGIN
    IF NOT is_master_device(p_master_device_id) THEN
        RAISE EXCEPTION 'Only the master station can change the extension policy';
    END IF;
    UPDATE app_settings
    SET auto_approve_extensions = CASE WHEN p_auto_approve = 1 THEN 1 ELSE 0 END,
        default_extension_modules = ARRAY(
            SELECT m FROM unnest(p_default_modules) AS m WHERE m NOT IN ('users', 'settings', 'devices')
        )
    WHERE id = 1;
    RETURN jsonb_build_object('success', true);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

GRANT EXECUTE ON FUNCTION register_device(TEXT, TEXT, TEXT, TEXT) TO authenticated;
GRANT EXECUTE ON FUNCTION master_heartbeat(TEXT) TO authenticated;
GRANT EXECUTE ON FUNCTION claim_master(TEXT) TO authenticated;
GRANT EXECUTE ON FUNCTION set_device_access(TEXT, TEXT, TEXT, TEXT[]) TO authenticated;
GRANT EXECUTE ON FUNCTION delete_device(TEXT, TEXT) TO authenticated;
GRANT EXECUTE ON FUNCTION set_extension_policy(TEXT, INT, TEXT[]) TO authenticated;
